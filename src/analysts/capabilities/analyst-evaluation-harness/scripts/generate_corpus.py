"""Generate the deterministic synthetic evaluation corpus (FR-016, research R9).

    python generate_corpus.py --output <empty dir>

Writes four clips per profile with the pinned FFmpeg ``testsrc2`` source and a ``corpus-manifest.json`` whose labels are
known by construction. Bit-exact encoder flags make two runs with the same toolchain byte-identical. The corpus is
generated, never committed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from analyst_evaluation_harness.corpus import manifest_identity  # noqa: E402

GENERATOR_VERSION = "1.0.0"
CORPUS_ID = "synthetic-testsrc2"
CORPUS_VERSION = "1.0.0"
MANIFEST_NAME = "corpus-manifest.json"
LABEL_KIND = "frame-second-probe"
DURATIONS_MS = (5000, 6000, 5000, 6000)
# Match-second aligned offsets keep every label on a fact boundary of the evaluated Analyst.
PROFILES = {
    "fixed": {"frame_rate": 25, "size": "64x64", "match_start_ms": (0, 0, 0, 0)},
    "broadcast": {"frame_rate": 30, "size": "128x72", "match_start_ms": (3000, 3000, 600000, 600000)},
}
EMPTY_LABELS_CLIP = ("fixed", 3)
EXIT_REFUSED = 2


def _ffmpeg_version() -> str:
    result = subprocess.run(["ffmpeg", "-version"], capture_output=True, text=True, check=True)
    return result.stdout.splitlines()[0].strip()


def _encode(path: Path, frame_rate: int, size: str, duration_ms: int) -> None:
    source = f"testsrc2=size={size}:rate={frame_rate}:duration={duration_ms / 1000:g}"
    subprocess.run(
        [
            "ffmpeg", "-nostdin", "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", source,
            "-c:v", "mpeg4", "-threads", "1", "-g", str(frame_rate), "-pix_fmt", "yuv420p",
            "-fflags", "+bitexact", "-flags:v", "+bitexact", "-map_metadata", "-1", "-an",
            str(path),
        ],
        check=True,
    )


def _digest(path: Path) -> str:
    return "sha-256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def _labels(frame_rate: int, duration_ms: int, match_start_ms: int) -> list[dict]:
    total_frames = round(duration_ms * frame_rate / 1000)
    labels = []
    for second in range((duration_ms + 999) // 1000):
        labels.append(
            {
                "labelKind": LABEL_KIND,
                "positionMs": match_start_ms + second * 1000,
                "payload": {"decodedFrames": min(frame_rate, total_frames - second * frame_rate)},
            }
        )
    return labels


def generate(output: Path) -> dict:
    if output.exists() and (not output.is_dir() or any(output.iterdir())):
        raise FileExistsError(f"output directory {output} must be empty")
    output.mkdir(parents=True, exist_ok=True)

    rights = {
        "origin": f"synthetic: generated by generate_corpus.py {GENERATOR_VERSION} with {_ffmpeg_version()}",
        "license": "no third-party rights",
        "production": "synthetic test data, not production data",
    }
    clips = []
    for profile, spec in PROFILES.items():
        for index, duration_ms in enumerate(DURATIONS_MS):
            clip_id = f"{profile}-{index + 1}"
            file = f"{clip_id}.mp4"
            _encode(output / file, spec["frame_rate"], spec["size"], duration_ms)
            match_start_ms = spec["match_start_ms"][index]
            empty = (profile, index) == EMPTY_LABELS_CLIP
            clips.append(
                {
                    "clipId": clip_id,
                    "file": file,
                    "digest": _digest(output / file),
                    "profile": profile,
                    "frameRate": spec["frame_rate"],
                    "durationMs": duration_ms,
                    "matchStartMs": match_start_ms,
                    "rights": dict(rights),
                    "labels": [] if empty else _labels(spec["frame_rate"], duration_ms, match_start_ms),
                }
            )

    manifest = {
        "manifestVersion": "1.0.0",
        "corpusId": CORPUS_ID,
        "corpusVersion": CORPUS_VERSION,
        "rights": rights,
        "clips": clips,
    }
    manifest["identity"] = manifest_identity(manifest)
    text = json.dumps(manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    (output / MANIFEST_NAME).write_text(text, encoding="utf-8", newline="\n")
    return manifest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the deterministic synthetic evaluation corpus.")
    parser.add_argument("--output", required=True, type=Path, help="empty directory to write the corpus into")
    arguments = parser.parse_args(argv)
    try:
        manifest = generate(arguments.output)
    except FileExistsError as exc:
        print(f"generate-corpus: {exc}", file=sys.stderr)
        return EXIT_REFUSED
    except (OSError, subprocess.CalledProcessError) as exc:
        print(f"generate-corpus: {exc}", file=sys.stderr)
        return 1
    print(f"{arguments.output / MANIFEST_NAME} {manifest['identity']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
